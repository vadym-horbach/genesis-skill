"""Generate references/output-schema.md from the Pydantic models (single source of truth).

    PYTHONPATH=src python dev/gen_schema.py          # write
    PYTHONPATH=src python dev/gen_schema.py --check  # exit 1 if the file is stale (used by tests)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from interest_signals import SCHEMA_VERSION
from interest_signals.models.envelope import Envelope
from interest_signals.models.request import AnalysisRequest
from interest_signals.models.result import AnalysisResult

OUT = Path(__file__).resolve().parent.parent / "references" / "output-schema.md"

HEADER = f"""# Output schema (v{SCHEMA_VERSION})

Generated by `dev/gen_schema.py` from the Pydantic models. Do not edit by hand.

Three contracts:

1. **Envelope**: the single JSON object printed to stdout. `status` is `ok`, `needs_confirmation`
   or `error`; exit codes 0, 2, 1. `summary.per_topic_language[].rationale` holds sentences to
   retell. `errors[]` and `warnings[]` items have `code`, `message`, `hint` (what to do next).
2. **AnalysisRequest**: what `--request FILE` accepts (and what `request.json` stores).
3. **AnalysisResult**: `analysis.json`, the canonical result. Charts and reports are rendered
   from it; follow-ups with `--render` reuse it without recomputation.

Key conventions:

- Pair key: `"<topic_id>:<project>"`, e.g. `"t1:pl.wikipedia"`.
- Months: `YYYY-MM`. Series arrays align with `months`. `status` per month is `ok`,
  `zero_filled` (page existed, no views recorded), `not_existing` (before page creation) or
  `unavailable` (API failure; never treated as zero).
- Growth values are fractions: `0.18` means +18%. `trend_*.annual_change` is per year.
- `per_million`: article views per 1M views of the same language edition in that month.
"""


def render() -> str:
    parts = [HEADER]
    for title, model in (("Envelope", Envelope), ("AnalysisRequest", AnalysisRequest),
                         ("AnalysisResult", AnalysisResult)):
        schema = model.model_json_schema(by_alias=True)
        parts.append(f"\n## {title}\n\n```json\n{json.dumps(schema, indent=1, ensure_ascii=False)}\n```\n")
    return "".join(parts)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("references/output-schema.md is stale; run dev/gen_schema.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
